TRANSLIT = str.maketrans({
    "a":"а","b":"б","c":"к","d":"д","e":"е","f":"ф","g":"г","h":"х","i":"и","j":"дж",
    "k":"к","l":"л","m":"м","n":"н","o":"о","p":"п","q":"к","r":"р","s":"с","t":"т",
    "u":"у","v":"в","w":"в","x":"кс","y":"й","z":"з",
})


def transliterate(word: str) -> str:
    result = ""
    for char in word:
        lower = char.lower()
        converted = lower.translate(TRANSLIT) if "a" <= lower <= "z" else char
        if char.isupper() and converted:
            converted = converted[0].upper() + converted[1:]
        result += converted
    return localize_game_text(result)


def translate_title(title: str) -> str:
    official = official_translations().get(re.sub(r"\s+", " ", re.sub(r"\[/?url(?:=[^]]+)?\]", "", title)).strip().replace("’", "'").casefold())
    if official:
        return localize_game_text(official)
    if title in EXACT_TITLES:
        return EXACT_TITLES[title]
    result = title
    for source, target in sorted(PHRASES.items(), key=lambda pair: len(pair[0]), reverse=True):
        result = re.sub(re.escape(source), target, result, flags=re.IGNORECASE)
    tokens = re.split(r"(\s+|[-–:(),'’])", result)
    translated: list[str] = []
    for token in tokens:
        key = token.casefold()
        if key in WORDS:
            value = WORDS[key]
            if token[:1].isupper():
                value = value[:1].upper() + value[1:]
            translated.append(value)
        elif re.search(r"[A-Za-z]", token):
            translated.append(transliterate(token))
        else:
            translated.append(token)
    result = re.sub(r"\s{2,}", " ", "".join(translated)).strip()
    result = re.sub(r"\s+([,:)])", r"\1", result)
    result = re.sub(r"([(])\s+", r"\1", result)
    return result


