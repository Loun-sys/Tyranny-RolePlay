const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const ctx=vm.createContext({document:{addEventListener(){}},esc:v=>String(v),data:{derived:{equipmentRecovery:.14,cooldownMultiplier:1}},expressionProfiles:{'Сосредоточенное намерение':{cooldown:2,projectiles:1}},spellSkillByCore:{},percentFrom:()=>0,numberFrom:()=>0});
vm.runInContext(fs.readFileSync('web/weapon-details.js','utf8'),ctx);
const gloves={name:'Железные рукавицы',category:'Броня',recovery:.06};
assert.equal(ctx.itemRecovery(gloves),.14,'current 0.09 -> 0.14, never one round');
assert.equal(ctx.itemRecovery({...gloves,recoveryAdapted:.14}),.14,'API value is not scaled again');
assert.equal(ctx.itemRecovery({recovery:.02}),.05,'half-cent rounding matches the backend');
assert.equal(ctx.itemRecovery({recovery:0}),0);
assert(ctx.itemGameStats(gloves).includes('+1,4 сек. (0,14 раунда)'));
assert(!ctx.itemGameStats({recovery:0}).includes('data-game-help="Восстановление"'));
const source=fs.readFileSync('web/archive.js','utf8');
vm.runInContext(source.split('\n').find(line=>line.startsWith('function spellNumbers(')),ctx);
assert.equal(ctx.spellNumbers({accents:[]},{attributes:{},skills:{}}).cooldown,2.14,'spell preview preserves fractional recovery');
ctx.data.derived.equipmentRecovery=1.8;
assert.equal(ctx.spellNumbers({accents:[]},{attributes:{},skills:{}}).cooldown,3.8);
ctx.data.derived.equipmentRecovery=0;
assert.equal(ctx.spellNumbers({accents:[]},{attributes:{},skills:{}}).cooldown,2);
assert(!source.includes('Округляется в большую сторону'));
assert(!source.includes('округлённое вверх восстановление'));
console.log('Equipment recovery: gloves 0.09 -> 0.14, API/fallback/zero stats and fractional spell preview OK');
