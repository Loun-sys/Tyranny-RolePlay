"""Adapt item instructions to roleplay without rewriting source lore or mechanics.

Only player-owned Spire facilities and their research/crafting instructions are
rewritten. Historical Spires, the Burning Library and ordinary smiths remain lore.
The extracted gameData/localization records must stay intact for source audits.
"""
import re


def adapt_item_copy(text):
    text = str(text or '')
    replacements = {
        'Обратитесь к мастеру-кузнецу в кузне Шпиля – возможно, он сможет поведать вам больше.':
            'Скованный Ремеслом может изучить этот предмет и определить, как его восстановить.',
        'Этот предмет можно улучшить в кузне Шпиля.':
            'Скованный Ремеслом может улучшить этот предмет.',
        'Вы можете это сделать, обладая доступом к библиотеке Шпиля и нужным материалам.': '',
        'Однако, чтобы восстановить чертеж целиком, нужно провести дополнительное исследование.':
            'Чертеж неполон и требует дальнейшего изучения.',
        'Однако, чтобы восстановить рецепт целиком, нужно провести дополнительное исследование.':
            'Рецепт неполон и требует дальнейшего изучения.',
        'Вы сможете расшифровать инструкции, если у вас есть доступ к библиотеке Шпиля и нужным материалам.':
            'Инструкции требуют расшифровки.',
        'Книгочеи перерыли множество старых текстов в вашей библиотеке в поисках чертежей могучих артефактов.':
            'В этом чертеже собраны сведения из старых текстов о могучих артефактах.',
        'Они наткнулись на несколько отрывков, в которых упоминал':
            'В этих текстах упоминал',
        'Книгочеи перерыли множество старых текстов в вашей библиотеке в поисках скрытых магических знаний.':
            'В этих записях собраны скрытые магические знания.',
        'Они нашли описание ритуала, который может пролить свет на то, как Кайрос повелевает Эдиктами.':
            'Описанный здесь ритуал может пролить свет на то, как Кайрос повелевает Эдиктами.',
        'Используя эти сведения и обретя достаточно веры, вы сможете создать Эдикт сами.': '',
        'Книгочеи полагают, что вы можете воссоздать': 'Скованный Ремеслом может воссоздать',
        'Книгочеи полагают, что умелый кузнец может воссоздать': 'Скованный Ремеслом может воссоздать',
        'Книгочеи полагают, что умелый портной может воссоздать': 'Скованный Ремеслом может воссоздать',
        'ваши Книгочеи нашли': 'Книгочеи нашли',
        'Этот кусок обсидиана можно использовать для изготовления мощного оружия в кузне Шпиля.':
            'Скованный Ремеслом может использовать этот кусок обсидиана для изготовления мощного оружия.',
    }
    for original, adapted in replacements.items():
        text = text.replace(original, adapted)
    text = re.sub(
        r'Скованный Ремеслом может воссоздать (.+?), если в процессе (.+?) нанесете на него нужные сигилы\.',
        r'Скованный Ремеслом может воссоздать \1, нанеся нужные сигилы в процессе \2.', text)
    text = re.sub(
        r'Этот рецепт позволяет (?:изготовлять|изготавливать|изготовить) (.+?), '
        r'если у вас есть доступ к лазарету Шпиля и нужным ингредиентам\.',
        r'По этому рецепту Скованный Ремеслом может изготовить \1 при наличии нужных ингредиентов.', text)
    text = re.sub(
        r'(?:Его|Их|Дротик) можно создать, если у вас есть доступ к кузне Шпиля и нужным материалам\.',
        'Скованный Ремеслом может изготовить это изделие при наличии нужных материалов.', text)
    text = re.sub(
        r'Вы можете (создать|вырастить) (.+?), если у вас есть доступ к лазарету Шпиля и нужным ингредиентам\.',
        r'Скованный Ремеслом может \1 \2 при наличии нужных ингредиентов.', text)
    # Legacy/custom descriptions may phrase the same instruction differently.
    forge = r'(?:в (?:своей|вашей|собственной) (?:кузне|кузнице)|в кузне Шпиля)'
    text = re.sub(rf'\bВы можете (изготовить|создать|скрафтить|выковать|улучшить) ([^.!?\n]+?) {forge}',
                  r'Скованный Ремеслом может \1 \2', text, flags=re.I)
    text = re.sub(forge, 'с помощью Скованного Ремеслом', text, flags=re.I)
    text = re.sub(r'в (?:своей|вашей|собственной) библиотеке', 'по этим записям', text, flags=re.I)
    return text.strip()


def adapt_item_properties(properties):
    """Clean visible property copy, not nested source components or numerical data."""
    def adapt(value):
        if isinstance(value, str):
            return adapt_item_copy(value)
        if isinstance(value, list):
            return [adapt(v) for v in value]
        if isinstance(value, dict):
            return {k: adapt(v) for k, v in value.items()}
        return value
    return {key: value if key == 'gameData' else adapt(value) for key, value in properties.items()}
