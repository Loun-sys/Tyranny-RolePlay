def adapt_item_properties(properties):
    """Clean visible property copy, not nested source components or numerical data."""
    def adapt(value):
        if isinstance(value, str):
            return adapt_item_copy(value)
        if isinstance(value, list):
            return [adapt(v) for v in value]
        if isinstance(value, dict):
            return {k: adapt(v) for k, v in value.items()}
        return value
    return {key: value if key == 'gameData' else adapt(value) for key, value in properties.items()}
